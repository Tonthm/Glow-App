/// Wednesday.
final now = DateTime(2026, 11, 25, 14);

String _time(int? minutes) => minutes == null
    ? '--'
    : '${(minutes ~/ 60).toString().padLeft(2, '0')}:'
          '${(minutes % 60).toString().padLeft(2, '0')}';

const _days = ['จ', 'อ', 'พ', 'พฤ', 'ศ', 'ส', 'อา'];
const _kinds = {
  ItemKind.classSession: 'เรียน',
  ItemKind.exam: 'สอบ',
  ItemKind.activity: 'กิจกรรม',
  ItemKind.holiday: 'หยุด',
};

/// "day start-end title [kind] ?uncertain fields" for compact expectations.
String describe(ParsedScheduleItem item) {
  final day = item.date != null
      ? '${item.date!.day}/${item.date!.month}/${item.date!.year}'
      : _days[item.weekday! - 1];
  final unsure = [
    for (final field in ParsedField.values)
      if (item.uncertain.contains(field)) field.name,
  ];
  final hours = item.startMinutes == null
      ? '----'
      : '${_time(item.startMinutes)}-${_time(item.endMinutes)}';
  return '$day $hours '
      '${item.title} [${_kinds[item.kind]}]'
      '${unsure.isEmpty ? '' : ' ?${unsure.join(',')}'}';
}

void expectItems(String sentence, List<String> expected) {
  final result = parseThaiSchedule(sentence, now: now);
  expect(result.items.map(describe).toList(), expected, reason: sentence);
}

void check(Map<String, List<String>> cases) {
  for (final entry in cases.entries) {
    test(entry.key, () => expectItems(entry.key, entry.value));
  }
}

