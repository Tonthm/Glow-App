    'สรุปบทเรียนประมาณชั่วโมงนึง ส่งวันเสาร์':
        'สรุปบทเรียน | 60 | 28/11 | อื่น',
    'การบ้านเลข สามสิบห้านาที': 'การบ้านเลข | 35 | - | การบ้าน',
  };

  for (final entry in cases.entries) {
    test(entry.key, () {
      expect(describe(parseSpokenTask(entry.key, now: now)), entry.value);
    });
  }

  test('estimates are rounded to 5-minute steps', () {
    expect(parseSpokenTask('อ่าน 22 นาที', now: now).minutes, 20);
    expect(parseSpokenTask('อ่าน 3 นาที', now: now).minutes, 5);
  });

  test('silence gives an empty task', () {
    final task = parseSpokenTask('  ', now: now);
    expect(task.title, isEmpty);
    expect(task.minutes, isNull);
  });
}
