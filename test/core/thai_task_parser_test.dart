import 'package:flutter_test/flutter_test.dart';
import 'package:glow/core/evening_planner.dart';
import 'package:glow/core/thai_task_parser.dart';

/// Wednesday.
final now = DateTime(2026, 11, 25, 17);

const _kinds = {
  EveningTaskKind.homework: 'การบ้าน',
  EveningTaskKind.reading: 'อ่าน',
  EveningTaskKind.examStudy: 'อ่านสอบ',
  EveningTaskKind.other: 'อื่น',
};

/// "title | minutes | due day/month | kind"
String describe(ParsedTask t) =>
    '${t.title} | ${t.minutes ?? '-'} | '
    '${t.due == null ? '-' : '${t.due!.day}/${t.due!.month}'} | '
    '${_kinds[t.kind]}';

void main() {
  const cases = {
    'การบ้านเลขสี่สิบนาทีส่งพรุ่งนี้': 'การบ้านเลข | 40 | 26/11 | การบ้าน',
    'การบ้านเลข 40 นาที ส่งพรุ่งนี้': 'การบ้านเลข | 40 | 26/11 | การบ้าน',
    'อ่านหนังสือประวัติศาสตร์ครึ่งชั่วโมง':
        'อ่านหนังสือประวัติศาสตร์ | 30 | - | อ่าน',
    'อ่านสอบฟิสิกส์ หนึ่งชั่วโมง': 'อ่านสอบฟิสิกส์ | 60 | - | อ่านสอบ',
    'อ่านสอบเคมีชั่วโมงครึ่ง': 'อ่านสอบเคมี | 90 | - | อ่านสอบ',
    'รายงานสังคม 1 ชั่วโมงครึ่ง ส่งวันศุกร์': 'รายงานสังคม | 90 | 27/11 | อื่น',
    'การบ้านอังกฤษ หนึ่งชั่วโมงครึ่ง': 'การบ้านอังกฤษ | 90 | - | การบ้าน',
    'โครงงานวิทย์ สองชั่วโมง ส่ง 15 ธันวา': 'โครงงานวิทย์ | 120 | 15/12 | อื่น',
    'โครงงาน 2 ชั่วโมง 15 นาที': 'โครงงาน | 135 | - | อื่น',
    'ท่องศัพท์ 15 นาที': 'ท่องศัพท์ | 15 | - | อื่น',
    'ท่องศัพท์สิบห้านาที': 'ท่องศัพท์ | 15 | - | อื่น',
    'การบ้านชีวะ 45 นาที ส่งมะรืน': 'การบ้านชีวะ | 45 | 27/11 | การบ้าน',
    'การบ้านชีวะ 45 นาที ส่งมะรืนนี้': 'การบ้านชีวะ | 45 | 27/11 | การบ้าน',
    'ใบงานไทย 20 นาที ส่งวันนี้': 'ใบงานไทย | 20 | 25/11 | การบ้าน',
    'ใบงานศิลปะ ครึ่งชม. ส่งวันจันทร์': 'ใบงานศิลปะ | 30 | 30/11 | การบ้าน',
    // Month-first isn't supported: keep the words rather than guess a date.
    'การบ้านคอม 1 ชม. ส่ง พ.ย. 30': 'การบ้านคอม ส่ง พ.ย. 30 | 60 | - | การบ้าน',
    'การบ้านคอม 1 ชม. ส่งวันที่ 30 พฤศจิกายน':
        'การบ้านคอม | 60 | 30/11 | การบ้าน',
    'การบ้านเลข ส่งพรุ่งนี้ 40 นาที': 'การบ้านเลข | 40 | 26/11 | การบ้าน',
    'พรุ่งนี้ส่งการบ้านเลข 40 นาที': 'การบ้านเลข | 40 | 26/11 | การบ้าน',
    'การบ้านฟิสิกส์': 'การบ้านฟิสิกส์ | - | - | การบ้าน',
    'อ่านนิยาย': 'อ่านนิยาย | - | - | อ่าน',
    'จัดกระเป๋า ๑๐ นาที': 'จัดกระเป๋า | 10 | - | อื่น',
    'ทบทวนเลขก่อนสอบ 30 นาที': 'ทบทวนเลขก่อนสอบ | 30 | - | อ่านสอบ',
